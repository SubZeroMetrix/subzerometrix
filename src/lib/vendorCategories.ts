// ── Helpers ────────────────────────────────────────────────────────────────────

export function getVendorById(id: string): VendorEntry | undefined {
  for (const cat of VENDOR_CATEGORIES) {
    const found = cat.vendors.find(v => v.id === id)
    if (found) return found
  }
  return undefined
}

export function getVendorsByCategory(categoryId: string): VendorEntry[] {
  return VENDOR_CATEGORIES.find(c => c.id === categoryId)?.vendors ?? []
}

export function getVendorsForPhase(vendorIds: string[]): VendorEntry[] {
  return vendorIds.map(id => getVendorById(id)).filter((v): v is VendorEntry => v !== undefined)
}

export function getCategoryById(id: string): VendorCategory | undefined {
  return VENDOR_CATEGORIES.find(c => c.id === id)
}
